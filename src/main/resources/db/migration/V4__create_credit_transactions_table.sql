CREATE TABLE credit_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_number VARCHAR(30) NOT NULL UNIQUE,
    credit_account_id BIGINT NOT NULL REFERENCES credit_accounts(id),
    created_by BIGINT REFERENCES users(id),
    amount NUMERIC(19,2) NOT NULL,
    description VARCHAR(255),
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL,
    voided_at TIMESTAMP,
    voided_by BIGINT REFERENCES users(id),

    CONSTRAINT chk_credit_transactions_amount CHECK (amount > 0),
    CONSTRAINT chk_status CHECK (status IN ('ACTIVE', 'VOIDED'))
);

CREATE SEQUENCE credit_transaction_ref_seq
        START WITH 1 INCREMENT BY 1;