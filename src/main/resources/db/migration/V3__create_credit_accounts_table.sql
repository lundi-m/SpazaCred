CREATE TABLE credit_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE REFERENCES customers(id),
    credit_limit NUMERIC(19,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,

    CONSTRAINT chk_credit_accounts_status CHECK(status IN ('ACTIVE', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT chk_credit_accounts_limit CHECK(credit_limit >= 0)
);